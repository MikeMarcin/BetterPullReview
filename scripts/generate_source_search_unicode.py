#!/usr/bin/env python3
"""Generate pinned Unicode 17 search tables from explicitly supplied UCD files.

No download occurs here. Ordinary builds consume the committed header.
"""
import argparse
import hashlib
from pathlib import Path

DIGESTS = {
    'CaseFolding.txt': 'ff8d8fefbf123574205085d6714c36149eb946d717a0c585c27f0f4ef58c4183',
    'UnicodeData.txt': '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
}
CATEGORIES = ['Lu','Ll','Lt','Lm','Lo','Mn','Mc','Me','Nd','Nl','No','Pc','Pd','Ps','Pe','Pi','Pf','Po','Sm','Sc','Sk','So','Zs','Zl','Zp','Cc','Cf','Cs','Co','Cn']


def generate(root):
    texts = {}
    for name, digest in DIGESTS.items():
        data = (root / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != digest:
            raise ValueError(f'{name} differs from pinned Unicode 17.0.0')
        texts[name] = data.decode('utf-8')
    folds = []
    for line in texts['CaseFolding.txt'].splitlines():
        fields = line.split('#')[0].split(';')
        if len(fields) > 2 and fields[1].strip() in ('C','S'):
            folds.append((int(fields[0],16), int(fields[2],16)))
    ranges = []
    pending = None
    for line in texts['UnicodeData.txt'].splitlines():
        fields = line.split(';')
        cp, name, category = int(fields[0],16), fields[1], CATEGORIES.index(fields[2])
        if name.endswith(', First>'):
            pending = cp
            continue
        begin = pending if name.endswith(', Last>') else cp
        pending = None
        if ranges and ranges[-1][1]+1 == begin and ranges[-1][2] == category:
            ranges[-1] = (ranges[-1][0], cp, category)
        else:
            ranges.append((begin, cp, category))
    lines = ['// Generated by scripts/generate_source_search_unicode.py; Unicode 17.0.0.',
             '// Copyright (c) 1991-2025 Unicode, Inc. SPDX-License-Identifier: Unicode-3.0',
             '// See third_party/unicode/LICENSE.txt. No locale or normalization is used.',
             '#ifndef BPR_SRC_CORE_SRC_SOURCE_SEARCH_UNICODE_DATA_HPP',
             '#define BPR_SRC_CORE_SRC_SOURCE_SEARCH_UNICODE_DATA_HPP',
             '#include <array>', '#include <cstdint>', 'namespace bpr::core::source_unicode {',
             'struct fold_pair { char32_t From; char32_t To; };',
             'struct category_range { char32_t Begin; char32_t End; std::uint8_t Category; };',
             'inline constexpr auto folds = std::array{']
    lines += [f'fold_pair{{0x{a:X}, 0x{b:X}}},' for a,b in folds]
    lines += ['};', 'inline constexpr auto reverse_folds = std::array{']
    lines += [f'fold_pair{{0x{b:X}, 0x{a:X}}},' for a,b in sorted(folds,key=lambda p:(p[1],p[0]))]
    lines += ['};', 'inline constexpr auto categories = std::array{']
    lines += [f'category_range{{0x{a:X}, 0x{b:X}, {c}}},' for a,b,c in ranges]
    lines += ['};','}', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--ucd-root',type=Path,required=True)
    parser.add_argument('--output',type=Path,required=True)
    args = parser.parse_args()
    args.output.write_text(generate(args.ucd_root),encoding='utf-8')

if __name__ == '__main__':
    main()
