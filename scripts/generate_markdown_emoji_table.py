#!/usr/bin/env python3
"""Writes the Markdown reader's emoji shortcode table from gemoji.

BPR-1544. GitHub writes `:+1:` as 👍 from its gemoji database. The reader
uses the same aliases from a pinned gemoji release, compiled in: nothing is
fetched at run time. This reads `db/emoji.json` from the release's source
archive, which must have the digest recorded below, and writes
`src/adapters/qt/src/markdown_emoji_table.inc`: every alias with its emoji,
sorted for a binary search, as escaped UTF-8 so the source stays ASCII.

Usage:
    generate_markdown_emoji_table.py <gemoji-4.1.0.tar.gz> <repository root>

The archive is
https://codeload.github.com/github/gemoji/tar.gz/refs/tags/v4.1.0
(see third_party/gemoji/PROVENANCE.md).
"""

from __future__ import annotations

import hashlib
import json
import sys
import tarfile
from pathlib import Path

ARCHIVE_SHA256 = "68c26ccc2901eca303f29d38efe65b66434f92461fb218a00fd7919fb7839c21"
DATABASE = "gemoji-4.1.0/db/emoji.json"
DATABASE_SHA256 = "b174ae2aeb321b52f64adb9ff412f966a7f338839d780784dd15dcad702c2dd6"
TARGET = "src/adapters/qt/src/markdown_emoji_table.inc"


def escaped(text: str) -> str:
    return "".join(f"\\x{byte:02x}" for byte in text.encode("utf-8"))


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    archive = Path(sys.argv[1])
    root = Path(sys.argv[2])
    data = archive.read_bytes()
    if hashlib.sha256(data).hexdigest() != ARCHIVE_SHA256:
        print("EMOJI_TABLE_REFUSED: the archive's digest is not gemoji 4.1.0's", file=sys.stderr)
        return 1
    with tarfile.open(archive) as bundle:
        member = bundle.extractfile(DATABASE)
        database = member.read() if member is not None else b""
    if hashlib.sha256(database).hexdigest() != DATABASE_SHA256:
        print("EMOJI_TABLE_REFUSED: db/emoji.json's digest is not gemoji 4.1.0's", file=sys.stderr)
        return 1
    entries: dict[str, str] = {}
    for item in json.loads(database):
        for alias in item["aliases"]:
            entries.setdefault(alias, item["emoji"])
    lines = [
        "// Generated by scripts/generate_markdown_emoji_table.py from gemoji 4.1.0",
        f"// (db/emoji.json sha256 {DATABASE_SHA256}). Do not edit.",
        "// gemoji is MIT licensed; third_party/gemoji retains its licence.",
        f"inline constexpr std::array<markdown_emoji_entry, {len(entries)}> markdown_emoji_table{{ {{",
    ]
    for alias in sorted(entries):
        lines.append(f'\t{{ "{alias}", "{escaped(entries[alias])}" }},')
    lines.append("} };")
    (root / TARGET).write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"EMOJI_TABLE_OK:{len(entries)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
